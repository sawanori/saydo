import Foundation

/// 記録タブの画面固有の文言。
///
/// 責める語を置かない（企画原則 §22-1）。件数・連続日数・達成率も出さない（§22-8）。
enum TimelineCopy {
    /// まだ 1 件も記録が無いときの 1 文。空白を責めず、これから溜まることだけを言う。
    static let empty = "ここに、あなたの声が残っていく。"

    /// 再生ボタンの読み上げラベル。
    static let play = "再生"
    /// 再生中の同じボタンの読み上げラベル。
    static let stop = "停止"
}
